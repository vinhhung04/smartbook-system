/**
 * Builds catalog-manifest.json - the book catalog the behavioural simulation
 * samples from - out of data/smartbook_catalog_enrichment_seed.sql, the real
 * inventory catalog dump that `pnpm demo:seed` loads into inventory_db.
 *
 * Why a committed manifest instead of reading the SQL at seed time: the
 * borrow-service Docker image (used by `demo-seed-borrow-history`) only copies
 * services/borrow-service, so the repo-level data/ directory is not reachable
 * from inside that container. The manifest is small, deterministic, and
 * checked by test/simulation-catalog.test.js so it cannot silently drift.
 *
 * USAGE (from services/borrow-service):
 *   node prisma/simulation/build-catalog-manifest.js
 */

const fs = require('fs');
const path = require('path');

const SQL_PATH = path.resolve(__dirname, '../../../../data/smartbook_catalog_enrichment_seed.sql');
const OUT_PATH = path.join(__dirname, 'catalog-manifest.json');

// Splits the VALUES (...) tuple of one INSERT line into raw SQL literals.
// Handles '' escapes inside strings; commas inside quotes are not separators.
function splitValues(tuple) {
  const values = [];
  let current = '';
  let inString = false;
  for (let i = 0; i < tuple.length; i += 1) {
    const ch = tuple[i];
    if (inString) {
      if (ch === "'" && tuple[i + 1] === "'") { current += "'"; i += 1; continue; }
      if (ch === "'") { inString = false; continue; }
      current += ch;
      continue;
    }
    if (ch === "'") { inString = true; continue; }
    if (ch === ',') { values.push(current.trim()); current = ''; continue; }
    current += ch;
  }
  values.push(current.trim());
  return values.map((v) => (v === 'NULL' ? null : v));
}

function parseInserts(sql, table) {
  const re = new RegExp(`^INSERT INTO public\\.${table} \\(([^)]*)\\) VALUES \\((.*)\\) ON CONFLICT DO NOTHING;$`, 'gm');
  const rows = [];
  let match;
  while ((match = re.exec(sql)) !== null) {
    const columns = match[1].split(',').map((c) => c.trim());
    const values = splitValues(match[2]);
    if (values.length !== columns.length) throw new Error(`${table}: column/value count mismatch`);
    rows.push(Object.fromEntries(columns.map((c, i) => [c, values[i]])));
  }
  return rows;
}

function buildManifest(sql) {
  const categories = parseInserts(sql, 'categories');
  const authors = parseInserts(sql, 'authors');
  const books = parseInserts(sql, 'books');
  const bookAuthors = parseInserts(sql, 'book_authors');
  const bookCategories = parseInserts(sql, 'book_categories');
  const variants = parseInserts(sql, 'book_variants');

  const categoryById = new Map(categories.map((c) => [c.id, c]));
  const authorById = new Map(authors.map((a) => [a.id, a]));

  const manifestBooks = books
    .filter((b) => b.is_active === 'true')
    .map((b) => {
      const bookVariants = variants
        .filter((v) => v.book_id === b.id && v.is_active === 'true' && v.is_borrowable === 'true')
        .map((v) => ({ id: v.id, sku: v.sku }))
        .sort((x, y) => x.sku.localeCompare(y.sku));
      const cats = bookCategories
        .filter((bc) => bc.book_id === b.id)
        .map((bc) => categoryById.get(bc.category_id))
        .filter(Boolean)
        .map((c) => c.slug);
      const auths = bookAuthors
        .filter((ba) => ba.book_id === b.id)
        .sort((x, y) => Number(x.author_order) - Number(y.author_order))
        .map((ba) => authorById.get(ba.author_id))
        .filter(Boolean)
        .map((a) => a.full_name);
      return {
        id: b.id,
        book_code: b.book_code,
        title: b.title,
        description: b.description || null,
        page_count: b.page_count === null ? null : Number(b.page_count),
        categories: cats.length ? cats : ['chua-phan-loai'],
        authors: auths,
        variants: bookVariants,
      };
    })
    .filter((b) => b.variants.length > 0)
    .sort((x, y) => (x.book_code || x.id).localeCompare(y.book_code || y.id));

  return {
    source: 'data/smartbook_catalog_enrichment_seed.sql',
    note: 'Generated by build-catalog-manifest.js - do not edit by hand.',
    categories: categories
      .map((c) => ({ id: c.id, slug: c.slug, name: c.name }))
      .sort((x, y) => x.slug.localeCompare(y.slug)),
    books: manifestBooks,
  };
}

if (require.main === module) {
  const manifest = buildManifest(fs.readFileSync(SQL_PATH, 'utf8'));
  fs.writeFileSync(OUT_PATH, `${JSON.stringify(manifest, null, 2)}\n`);
  const variantCount = manifest.books.reduce((n, b) => n + b.variants.length, 0);
  console.log(`[catalog] ${manifest.books.length} books, ${variantCount} borrowable variants, ${manifest.categories.length} categories -> ${OUT_PATH}`);
}

module.exports = { buildManifest, parseInserts, splitValues, SQL_PATH };
