// SB-02 concurrency proof: fires real parallel HTTP requests against a running
// stack (docker compose up) and asserts on both the HTTP outcomes and the
// final Postgres state. Three scenarios:
//   1. DoD race: N concurrent reservations against available_qty=1 stock —
//      exactly 1 must win.
//   2/3. Repro for the two bugs fixed alongside SB-01/SB-02: concurrent
//      release/consume of the same reservation, and concurrent approval of
//      the same stock audit, must each apply their effect exactly once.
//
// Requires the full docker compose stack running (`docker compose up -d`,
// `pnpm demo:seed`) — reads .env directly like scripts/init-demo-env.mjs and
// scripts/seed-catalog-enrichment.mjs so it works the same from any shell.
import crypto from 'node:crypto';
import { readFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { spawnSync } from 'node:child_process';

const root = resolve(import.meta.dirname, '..');
const envPath = resolve(root, '.env');
const baseUrl = process.env.BASE_URL || 'http://localhost:3000';

function readEnvVar(name, fallback) {
  if (!existsSync(envPath)) return fallback;
  const contents = readFileSync(envPath, 'utf8');
  const match = contents.match(new RegExp(`^${name}=(.*)$`, 'm'));
  return match ? match[1].trim() : fallback;
}

const dbUser = readEnvVar('DB_USER', 'user');
const inventoryDbName = readEnvVar('INVENTORY_DB_NAME', 'inventory_db');
// The running stack's .env carries the real JWT_SECRET (generated by
// `pnpm demo:env`), not the 'smartbook_shared_jwt_secret' placeholder some
// older scripts default to — read it directly so this script works against
// any stack regardless of how JWT_SECRET was generated.
const jwtSecret = process.env.JWT_SECRET || readEnvVar('JWT_SECRET', 'smartbook_shared_jwt_secret');

function psql(sql) {
  const result = spawnSync(
    'docker',
    ['compose', 'exec', '-T', 'db', 'psql', '-U', dbUser, '-d', inventoryDbName, '-v', 'ON_ERROR_STOP=1', '-t', '-A', '-F', '|'],
    { cwd: root, input: sql, encoding: 'utf8' },
  );
  if (result.status !== 0) {
    throw new Error(`psql failed (status ${result.status}): ${result.stderr || result.stdout}`);
  }
  return result.stdout.trim();
}

function psqlRows(sql) {
  const out = psql(sql);
  if (!out) return [];
  return out.split('\n').filter(Boolean).map((line) => line.split('|'));
}

function b64url(input) {
  return Buffer.from(input).toString('base64').replace(/=/g, '').replace(/\+/g, '-').replace(/\//g, '_');
}

function signJwt(payload, secret) {
  const header = { alg: 'HS256', typ: 'JWT' };
  const encodedHeader = b64url(JSON.stringify(header));
  const encodedPayload = b64url(JSON.stringify(payload));
  const signingInput = `${encodedHeader}.${encodedPayload}`;
  const signature = crypto.createHmac('sha256', secret).update(signingInput).digest('base64')
    .replace(/=/g, '').replace(/\+/g, '-').replace(/\//g, '_');
  return `${signingInput}.${signature}`;
}

const testActorId = crypto.randomUUID();
const token = signJwt({
  id: testActorId,
  email: `concurrency.itest.${Date.now()}@smartbook.local`,
  full_name: 'Concurrency Test Admin',
  is_superuser: true,
  permissions: ['borrow.read', 'borrow.write', 'inventory.stock.read', 'inventory.stock.write', 'inventory.audit.read', 'inventory.audit.approve'],
  iat: Math.floor(Date.now() / 1000),
  exp: Math.floor(Date.now() / 1000) + 4 * 60 * 60,
}, jwtSecret);

function makeHeaders(extra = {}) {
  return { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json', ...extra };
}

async function request(method, path, body, extraHeaders = {}) {
  const response = await fetch(`${baseUrl}${path}`, {
    method,
    headers: makeHeaders(extraHeaders),
    body: body == null ? undefined : JSON.stringify(body),
  });
  const data = await response.json().catch(() => ({}));
  return { ok: response.ok, status: response.status, data };
}

function idemHeader() {
  return { 'Idempotency-Key': crypto.randomUUID() };
}

const results = [];
function add(name, ok, detail) {
  results.push({ name, ok, detail });
  console.log(`${ok ? 'PASS' : 'FAIL'} - ${name}${detail ? ` :: ${detail}` : ''}`);
}

async function resolveTarget() {
  const rows = psqlRows(`
    SELECT sb.variant_id, sb.warehouse_id, sb.location_id
    FROM stock_balances sb
    JOIN book_variants bv ON bv.id = sb.variant_id
    WHERE sb.available_qty > 0 AND bv.is_borrowable = true
    ORDER BY sb.available_qty DESC
    LIMIT 1;
  `);
  if (rows.length === 0) {
    throw new Error('No borrowable variant with available stock found in inventory_db');
  }
  const [variant_id, warehouse_id, location_id] = rows[0];
  return { variant_id, warehouse_id, location_id };
}

function setBalance(target, { available_qty, reserved_qty }) {
  psql(`
    UPDATE stock_balances
    SET available_qty = ${available_qty}, reserved_qty = ${reserved_qty}
    WHERE variant_id = '${target.variant_id}' AND location_id = '${target.location_id}';
  `);
}

function readBalance(target) {
  const rows = psqlRows(`
    SELECT available_qty, reserved_qty, borrowed_qty
    FROM stock_balances
    WHERE variant_id = '${target.variant_id}' AND location_id = '${target.location_id}';
  `);
  const [available_qty, reserved_qty, borrowed_qty] = rows[0].map(Number);
  return { available_qty, reserved_qty, borrowed_qty };
}

async function createTestCustomer(index) {
  const response = await request('POST', '/borrow/customers', {
    full_name: `Concurrency Test Customer ${index}`,
    email: `concurrency.itest.${Date.now()}.${index}@smartbook.local`,
    status: 'ACTIVE',
  });
  if (!response.ok || !response.data?.data?.id) {
    throw new Error(`Failed to create test customer ${index}: ${JSON.stringify(response.data)}`);
  }
  return response.data.data.id;
}

// Scenario 1 — roadmap DoD: N concurrent reservations against available_qty=1
// must yield exactly 1 success and leave the balance at available_qty=0,
// reserved_qty=1.
async function scenarioReservationRace(target) {
  const N = 6;
  setBalance(target, { available_qty: 1, reserved_qty: 0 });

  const customerIds = [];
  for (let i = 0; i < N; i += 1) {
    customerIds.push(await createTestCustomer(`race-${i}`));
  }

  const responses = await Promise.all(customerIds.map((customer_id) => request(
    'POST',
    '/borrow/reservations',
    {
      customer_id,
      variant_id: target.variant_id,
      warehouse_id: target.warehouse_id,
      quantity: 1,
      source_channel: 'COUNTER',
      notes: 'concurrency race integration test',
    },
    idemHeader(),
  )));

  const succeeded = responses.filter((r) => r.status === 201);
  const conflicted = responses.filter((r) => r.status === 409);

  add(
    '1. exactly 1 of 6 concurrent reservations succeeds (201), rest 409',
    succeeded.length === 1 && conflicted.length === N - 1,
    `201=${succeeded.length} 409=${conflicted.length} other=${responses.length - succeeded.length - conflicted.length}`,
  );

  const finalBalance = readBalance(target);
  add(
    '1. final stock_balances is available_qty=0, reserved_qty=1',
    finalBalance.available_qty === 0 && finalBalance.reserved_qty === 1,
    JSON.stringify(finalBalance),
  );

  return succeeded[0]?.data?.data?.id || null;
}

// Scenario 2 — Bug 1 repro: releaseBorrowReservation. Reuses the winning
// reservation from scenario 1 (its stock_reservations row is ACTIVE,
// reserved_qty=1 at the target location) and fires concurrent /release calls
// directly at inventory-service with the same reservation_id.
async function scenarioReleaseRace(reservationId) {
  const N = 5;
  const responses = await Promise.all(Array.from({ length: N }, () => request(
    'POST',
    '/api/borrow-integration/reservations/release',
    { reservation_id: reservationId, reason: 'CANCELLED', idempotency_key: crypto.randomUUID() },
  )));

  const succeeded = responses.filter((r) => r.ok);
  const conflicted = responses.filter((r) => r.status === 409);

  add(
    '2. exactly 1 of 5 concurrent releases applies the stock effect',
    succeeded.length >= 1 && conflicted.length === N - succeeded.length,
    `ok=${succeeded.length} 409=${conflicted.length}`,
  );
}

// Scenario 3 — Bug 1 repro: consumeBorrowReservation. Seeds a fresh ACTIVE
// stock_reservations row directly at inventory-service (bypassing
// borrow-service entirely) then fires concurrent /consume calls.
async function scenarioConsumeRace(target) {
  const N = 5;
  setBalance(target, { available_qty: 1, reserved_qty: 0 });

  const reservationId = crypto.randomUUID();
  const reserve = await request('POST', '/api/borrow-integration/reservations/reserve', {
    reservation_id: reservationId,
    reservation_number: `RSV-RACE-${Date.now()}`,
    variant_id: target.variant_id,
    warehouse_id: target.warehouse_id,
    quantity: 1,
    expires_at: new Date(Date.now() + 24 * 60 * 60 * 1000).toISOString(),
    idempotency_key: crypto.randomUUID(),
  });
  if (!reserve.ok) {
    throw new Error(`Failed to seed reservation for consume race: ${JSON.stringify(reserve.data)}`);
  }

  const responses = await Promise.all(Array.from({ length: N }, () => request(
    'POST',
    '/api/borrow-integration/reservations/consume',
    {
      reservation_id: reservationId,
      loan_id: crypto.randomUUID(),
      loan_number: `LN-RACE-${Date.now()}`,
      warehouse_id: target.warehouse_id,
      idempotency_key: crypto.randomUUID(),
    },
  )));

  const succeeded = responses.filter((r) => r.status === 201);
  const conflicted = responses.filter((r) => r.status === 409);

  add(
    '3. exactly 1 of 5 concurrent consumes applies the stock effect',
    succeeded.length === 1 && conflicted.length === N - 1,
    `201=${succeeded.length} 409=${conflicted.length}`,
  );

  const finalBalance = readBalance(target);
  add(
    '3. final stock_balances is reserved_qty=0, borrowed_qty incremented exactly once',
    finalBalance.reserved_qty === 0 && finalBalance.borrowed_qty >= 1,
    JSON.stringify(finalBalance),
  );
}

// Scenario 4 — Bug 2 repro: approveStockAudit. Creates an audit scoped to the
// target location (which may hold more than one stock_balances line — every
// line must be counted before submit), gives exactly one line a non-zero
// variance, submits, then fires concurrent /approve calls.
async function scenarioStockAuditApprovalRace(target) {
  const N = 5;

  const created = await request('POST', '/api/stock-audits', {
    warehouse_id: target.warehouse_id,
    location_ids: [target.location_id],
    note: 'concurrency race integration test',
  });
  if (!created.ok || !created.data?.data?.id) {
    throw new Error(`Failed to create stock audit: ${JSON.stringify(created.data)}`);
  }
  const auditId = created.data.data.id;

  const detail = await request('GET', `/api/stock-audits/${auditId}`);
  const lines = detail.data?.data?.items || [];
  if (lines.length === 0) {
    throw new Error(`Stock audit ${auditId} has no lines: ${JSON.stringify(detail.data)}`);
  }

  const varianceLine = lines[0];
  for (const line of lines) {
    const countedQty = line.id === varianceLine.id ? Number(line.expected_qty) + 3 : Number(line.expected_qty);
    const counted = await request('PATCH', `/api/stock-audits/${auditId}/lines/${line.id}`, { counted_qty: countedQty });
    if (!counted.ok) {
      throw new Error(`Failed to submit line count for ${line.id}: ${JSON.stringify(counted.data)}`);
    }
  }
  const line = varianceLine;

  const submitted = await request('PATCH', `/api/stock-audits/${auditId}/submit`);
  if (!submitted.ok) {
    throw new Error(`Failed to submit stock audit: ${JSON.stringify(submitted.data)}`);
  }

  const responses = await Promise.all(Array.from({ length: N }, () => request(
    'PATCH',
    `/api/stock-audits/${auditId}/approve`,
  )));

  const nonIdempotentSuccesses = responses.filter((r) => r.ok && !r.data?.idempotent && (r.data?.data?.adjustments_posted || 0) > 0);
  const idempotentReplays = responses.filter((r) => r.ok && r.data?.idempotent);

  add(
    '4. exactly 1 of 5 concurrent approvals applies the adjustment; rest are idempotent replays',
    nonIdempotentSuccesses.length === 1 && idempotentReplays.length === N - 1,
    `applied=${nonIdempotentSuccesses.length} idempotent=${idempotentReplays.length} other=${responses.length - nonIdempotentSuccesses.length - idempotentReplays.length}`,
  );

  const movementCount = psqlRows(`
    SELECT COUNT(*) FROM stock_movements
    WHERE reference_type = 'stock_audit' AND reference_id = '${line.id}';
  `)[0]?.[0];
  add(
    '4. exactly 1 stock_movements row was posted for the audited line',
    Number(movementCount) === 1,
    `stock_movements count=${movementCount}`,
  );
}

// This is a shared dev/demo database — snapshot every stock_balances row at
// the target location before mutating anything, and restore them all when
// done (pass or fail), so this script doesn't leave other integration
// scripts (which expect real available stock) unable to find a target.
function snapshotLocationBalances(locationId) {
  return psqlRows(`
    SELECT id, available_qty, reserved_qty, borrowed_qty, on_hand_qty
    FROM stock_balances WHERE location_id = '${locationId}';
  `).map(([id, available_qty, reserved_qty, borrowed_qty, on_hand_qty]) => ({
    id, available_qty: Number(available_qty), reserved_qty: Number(reserved_qty),
    borrowed_qty: Number(borrowed_qty), on_hand_qty: Number(on_hand_qty),
  }));
}

function restoreLocationBalances(snapshot) {
  for (const row of snapshot) {
    psql(`
      UPDATE stock_balances
      SET available_qty = ${row.available_qty}, reserved_qty = ${row.reserved_qty},
          borrowed_qty = ${row.borrowed_qty}, on_hand_qty = ${row.on_hand_qty}
      WHERE id = '${row.id}';
    `);
  }
}

async function run() {
  const target = await resolveTarget();
  console.log(`Target: variant=${target.variant_id} warehouse=${target.warehouse_id} location=${target.location_id}`);
  const snapshot = snapshotLocationBalances(target.location_id);

  try {
    const winningReservationId = await scenarioReservationRace(target);
    if (winningReservationId) {
      await scenarioReleaseRace(winningReservationId);
    } else {
      add('2. exactly 1 of 5 concurrent releases applies the stock effect', false, 'skipped: scenario 1 had no winning reservation');
    }

    await scenarioConsumeRace(target);
    await scenarioStockAuditApprovalRace(target);
  } finally {
    restoreLocationBalances(snapshot);
    console.log(`Restored ${snapshot.length} stock_balances row(s) at location ${target.location_id} to pre-test values.`);
  }

  console.table(results);
  const pass = results.filter((r) => r.ok).length;
  console.log(`PASS=${pass} TOTAL=${results.length}`);
  process.exitCode = pass === results.length ? 0 : 1;
}

run().catch((error) => {
  console.error('Unhandled error in reservation-concurrency-race-integration:', error);
  process.exitCode = 1;
});
