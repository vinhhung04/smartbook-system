// Builds data/smartbook_catalog_expansion.sql from data/catalog-expansion-books.json.
//
// The JSON holds real books, every one with a real cover photo: found through
// SmartBook's own ISBN lookup (POST /ai/lookup-book-by-isbn) when the retailer
// listing carries a real barcode, otherwise taken from that Tiki product page
// (no ISBN is invented; the variant is keyed by the Tiki product id). The SQL adds, idempotently:
//   - new branches and warehouses with shelves (locations),
//   - those books (publishers, authors, categories, one variant each),
//   - opening stock: a posted MANUAL goods receipt per site, its lines, the
//     INBOUND stock movements and the stock balances they produce. New books go
//     to several branches and warehouses; every existing book with a cover also
//     gets copies on the new branches' shelves.
// Ids are derived from stable keys (ISBN, site code), so re-running the SQL —
// or regenerating it from the same JSON — changes nothing.
//
//   node scripts/build-catalog-expansion.mjs
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const books = JSON.parse(readFileSync(resolve(root, "data", "catalog-expansion-books.json"), "utf8"));
const outPath = resolve(root, "data", "smartbook_catalog_expansion.sql");

const HOURS = "Thứ 2 – Thứ 7: 8:00 – 20:00 · Chủ nhật: 8:00 – 17:00";
const BRANCHES = [
  { code: "BR-HCM-03", name: "Chi nhánh Thủ Đức", line1: "1 Võ Văn Ngân", ward: "Linh Chiểu", district: "TP. Thủ Đức", province: "TP. Hồ Chí Minh" },
  { code: "BR-HN-01", name: "Chi nhánh Hà Nội – Cầu Giấy", line1: "144 Xuân Thủy", ward: "Dịch Vọng Hậu", district: "Cầu Giấy", province: "Hà Nội" },
  { code: "BR-HN-02", name: "Chi nhánh Hà Nội – Hoàn Kiếm", line1: "40 Tràng Tiền", ward: "Tràng Tiền", district: "Hoàn Kiếm", province: "Hà Nội" },
  { code: "BR-DN-01", name: "Chi nhánh Đà Nẵng", line1: "155 Nguyễn Văn Linh", ward: "Nam Dương", district: "Hải Châu", province: "Đà Nẵng" },
];
const WAREHOUSES = [
  { code: "WH-DN-01", name: "Kho Đà Nẵng", line1: "Lô 12, KCN Hòa Khánh", ward: "Hòa Khánh Bắc", district: "Liên Chiểu", province: "Đà Nẵng" },
  { code: "WH-CT-01", name: "Kho Cần Thơ", line1: "Lô 5, KCN Trà Nóc 1", ward: "Trà Nóc", district: "Bình Thủy", province: "Cần Thơ" },
];
// Sites that receive the new books (existing ones included).
const BRANCH_SITES = ["BR-HCM-01", "BR-HCM-02", ...BRANCHES.map((b) => b.code)];
const WAREHOUSE_SITES = ["WH-HCM-01", "WH-HN-01", ...WAREHOUSES.map((w) => w.code)];
const BRANCH_SHELVES = ["BR-SHELF-01", "BR-SHELF-02", "BR-SHELF-03"];

/** RFC 4122 v5-style UUID from a stable key. */
function uuidFor(key) {
  const hex = createHash("sha1").update(`smartbook-expansion:${key}`).digest("hex").slice(0, 32).split("");
  hex[12] = "5";
  hex[16] = ((parseInt(hex[16], 16) & 0x3) | 0x8).toString(16);
  const h = hex.join("");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20, 32)}`;
}
/** Deterministic integer from a key (for stock placement). */
function hashInt(key) {
  return parseInt(createHash("md5").update(key).digest("hex").slice(0, 8), 16);
}
/** Stable key, SKU and barcode: the ISBN when the book has one, else its Tiki product id. */
const keyOf = (book) => (book.isbn ? book.isbn : `tiki-${book.tiki_id}`);
const skuOf = (book) => (book.isbn ? `IMPORT-${book.isbn}` : `TIKI-${book.tiki_id}`);
const q = (value) => (value === null || value === undefined || value === "" ? "NULL" : `'${String(value).replace(/'/g, "''")}'`);
const n = (value) => (Number.isFinite(Number(value)) && value !== null && value !== "" ? String(Number(value)) : "NULL");

const sql = [];
sql.push(`-- GENERATED by scripts/build-catalog-expansion.mjs from data/catalog-expansion-books.json — do not edit by hand.
-- Applied by scripts/seed-catalog-enrichment.mjs after the base fix. Idempotent.
BEGIN;
`);

// ── sites ──
sql.push("-- ── new branches and warehouses ──");
for (const [type, sites] of [["BRANCH", BRANCHES], ["WAREHOUSE", WAREHOUSES]]) {
  for (const site of sites) {
    sql.push(`INSERT INTO warehouses (id, code, name, warehouse_type, address_line1, ward, district, province, country, opening_hours, is_active)
VALUES (${q(uuidFor(`warehouse:${site.code}`))}, ${q(site.code)}, ${q(site.name)}, '${type}', ${q(site.line1)}, ${q(site.ward)}, ${q(site.district)}, ${q(site.province)}, 'Vietnam', ${type === "BRANCH" ? q(HOURS) : "NULL"}, true)
ON CONFLICT (code) DO NOTHING;`);
  }
}

// ── locations ── (branch: flat shelf compartments; warehouse: zone > shelf > compartment)
sql.push("\n-- ── shelves ──");
const location = (siteCode, code, type, opts = {}) => `INSERT INTO locations (id, warehouse_id, parent_location_id, location_code, location_type, zone, aisle, shelf, bin, barcode, capacity_qty, is_pickable)
SELECT ${q(uuidFor(`location:${siteCode}:${code}`))}, w.id, ${opts.parent ? `(SELECT id FROM locations WHERE warehouse_id = w.id AND location_code = ${q(opts.parent)})` : "NULL"}, ${q(code)}, '${type}', ${q(opts.zone)}, ${q(opts.aisle)}, ${q(opts.shelf)}, ${q(opts.bin)}, ${q(`LOC-${siteCode}-${code}`)}, ${n(opts.capacity)}, ${opts.pickable === false ? "false" : "true"}
FROM warehouses w WHERE w.code = ${q(siteCode)}
ON CONFLICT DO NOTHING;`;
for (const siteCode of BRANCH_SITES) {
  for (const shelf of BRANCH_SHELVES) sql.push(location(siteCode, shelf, "SHELF_COMPARTMENT", { capacity: 120 }));
}
for (const site of BRANCHES) sql.push(location(site.code, "RECEIVING-01", "RECEIVING", { zone: "RECEIVING", pickable: false }));
for (const site of WAREHOUSES) {
  sql.push(location(site.code, "RECEIVING-01", "RECEIVING", { pickable: false }));
  sql.push(location(site.code, "ZONE-A", "ZONE", { zone: "A", pickable: false }));
  sql.push(location(site.code, "SHELF-A-01", "SHELF", { parent: "ZONE-A", zone: "A", aisle: "01", pickable: false }));
  for (const bin of ["001", "002"]) sql.push(location(site.code, `A-01-${bin}`, "SHELF_COMPARTMENT", { parent: "SHELF-A-01", zone: "A", aisle: "01", shelf: bin, bin: "A", capacity: 200 }));
}
// Existing warehouses get a compartment of their own for the opening stock.
for (const siteCode of ["WH-HCM-01", "WH-HN-01"]) {
  sql.push(location(siteCode, "EXP-A-01", "SHELF_COMPARTMENT", { capacity: 300 }));
}

// ── catalog ──
sql.push("\n-- ── publishers and authors ──");
const publishers = [...new Set(books.map((b) => b.publisher).filter(Boolean))];
for (const name of publishers) {
  sql.push(`INSERT INTO publishers (id, code, name, country) VALUES (${q(uuidFor(`publisher:${name}`))}, ${q(`PUB-EXP-${hashInt(name).toString(36).toUpperCase()}`)}, ${q(name)}, 'Vietnam') ON CONFLICT DO NOTHING;`);
}
const authors = [...new Set(books.flatMap((b) => b.authors || []))];
for (const name of authors) {
  sql.push(`INSERT INTO authors (id, full_name) VALUES (${q(uuidFor(`author:${name}`))}, ${q(name)}) ON CONFLICT DO NOTHING;`);
}

sql.push("\n-- ── books (skipped when the ISBN is already in the catalog) ──");
for (const book of books) {
  const key = keyOf(book);
  const bookId = uuidFor(`book:${key}`);
  const variantId = uuidFor(`variant:${key}`);
  const sku = skuOf(book);
  const barcode = book.isbn || sku;
  const absent = `NOT EXISTS (SELECT 1 FROM book_variants v WHERE v.sku = ${q(sku)} OR v.internal_barcode = ${q(barcode)}${book.isbn ? ` OR v.isbn13 = ${q(book.isbn)}` : ""})`;
  const metadata = JSON.stringify({ source: "catalog-expansion", lookup_sources: book.sources || [], source_url: book.source_url || undefined });
  sql.push(`INSERT INTO books (id, title, subtitle, description, publisher_id, published_date, page_count, default_language, is_active, metadata)
SELECT ${q(bookId)}, ${q(book.title)}, ${q(book.subtitle)}, ${q(book.description)}, (SELECT id FROM publishers WHERE name = ${q(book.publisher)}), ${book.publish_year ? q(`${book.publish_year}-01-01`) : "NULL"}, ${n(book.page_count)}, ${q(book.language || "vi")}, true, ${q(metadata)}::jsonb
WHERE ${absent} AND NOT EXISTS (SELECT 1 FROM books WHERE id = ${q(bookId)});
INSERT INTO book_variants (id, book_id, sku, isbn13, internal_barcode, cover_type, language_code, publish_year, condition_grade, unit_cost, list_price, replacement_cost, is_borrowable, is_sellable, cover_image_url, is_active)
SELECT ${q(variantId)}, ${q(bookId)}, ${q(sku)}, ${q(book.isbn)}, ${q(barcode)}, 'PAPERBACK', ${q(book.language || "vi")}, ${n(book.publish_year)}, 'NEW', ${n(Math.round((book.list_price || 0) * 0.7))}, ${n(book.list_price || 0)}, ${n(book.list_price || 0)}, true, false, ${q(book.cover_image_url)}, true
WHERE EXISTS (SELECT 1 FROM books WHERE id = ${q(bookId)}) AND ${absent};`);
  // The JSON stays the source of truth for the description of books this seed created.
  sql.push(`UPDATE books SET description = ${q(book.description)}, updated_at = now() WHERE id = ${q(bookId)} AND metadata->>'source' = 'catalog-expansion' AND description IS DISTINCT FROM ${q(book.description)};`);
  // Fill a publisher the first run could not resolve (re-runs only ever fill blanks).
  if (book.publisher) {
    sql.push(`UPDATE books SET publisher_id = (SELECT id FROM publishers WHERE name = ${q(book.publisher)}), updated_at = now() WHERE id = ${q(bookId)} AND publisher_id IS NULL AND EXISTS (SELECT 1 FROM publishers WHERE name = ${q(book.publisher)});`);
  }
  (book.authors || []).forEach((name, index) => {
    sql.push(`INSERT INTO book_authors (book_id, author_id, author_order) SELECT ${q(bookId)}, a.id, ${index + 1} FROM authors a WHERE a.full_name = ${q(name)} AND EXISTS (SELECT 1 FROM books WHERE id = ${q(bookId)}) ON CONFLICT DO NOTHING;`);
  });
  sql.push(`INSERT INTO book_categories (book_id, category_id) SELECT ${q(bookId)}, c.id FROM categories c WHERE c.slug = ${q(book.category_slug)} AND EXISTS (SELECT 1 FROM books WHERE id = ${q(bookId)}) ON CONFLICT DO NOTHING;`);
}

// ── opening stock ──
sql.push(`
-- ── opening stock ──
CREATE TEMP TABLE sb_open_stock (site_code text, sku text, location_code text, qty int) ON COMMIT DROP;`);
const rows = [];
for (const book of books) {
  const key = keyOf(book);
  const sku = skuOf(book);
  // 3–4 branches, 2–5 copies each, on one of the branch shelves.
  const branchCount = 3 + (hashInt(`${key}:nb`) % 2);
  const start = hashInt(`${key}:b`) % BRANCH_SITES.length;
  for (let i = 0; i < branchCount; i += 1) {
    const site = BRANCH_SITES[(start + i * 2) % BRANCH_SITES.length];
    rows.push([site, sku, BRANCH_SHELVES[hashInt(`${key}:${site}:s`) % BRANCH_SHELVES.length], 2 + (hashInt(`${key}:${site}:q`) % 4)]);
  }
  // 1–2 warehouses, 6–15 copies.
  const whStart = hashInt(`${key}:w`) % WAREHOUSE_SITES.length;
  for (let i = 0; i < 1 + (hashInt(`${key}:nw`) % 2); i += 1) {
    const site = WAREHOUSE_SITES[(whStart + i) % WAREHOUSE_SITES.length];
    const loc = site.startsWith("WH-HCM") || site.startsWith("WH-HN") ? "EXP-A-01" : `A-01-00${1 + (hashInt(`${key}:${site}:s`) % 2)}`;
    rows.push([site, sku, loc, 6 + (hashInt(`${key}:${site}:q`) % 10)]);
  }
}
sql.push(`INSERT INTO sb_open_stock (site_code, sku, location_code, qty) VALUES\n${rows.map((r) => `  (${q(r[0])}, ${q(r[1])}, ${q(r[2])}, ${r[3]})`).join(",\n")};`);
sql.push(`-- Every existing book with a cover also opens on two of the new branches (2–4 copies).
INSERT INTO sb_open_stock (site_code, sku, location_code, qty)
SELECT site.code, v.sku, 'BR-SHELF-0' || (1 + abs(hashtext(v.sku || site.code)) % 3), 2 + abs(hashtext(v.sku || site.code || 'q')) % 3
FROM book_variants v
JOIN books b ON b.id = v.book_id AND b.is_active
CROSS JOIN (VALUES ${BRANCHES.map((b, i) => `(${q(b.code)}, ${i})`).join(", ")}) AS site(code, idx)
WHERE v.is_active AND v.cover_image_url IS NOT NULL AND v.sku NOT IN (SELECT sku FROM sb_open_stock)
  AND (abs(hashtext(v.sku)) % ${BRANCHES.length} = site.idx OR abs(hashtext(v.sku)) % ${BRANCHES.length} = (site.idx + 1) % ${BRANCHES.length});

-- One posted manual receipt per site carries the opening stock.
INSERT INTO goods_receipts (id, receipt_number, warehouse_id, source_type, status, received_at, note)
SELECT md5('smartbook-expansion:receipt:' || w.code)::uuid, 'GR-OPEN-' || w.code, w.id, 'MANUAL', 'POSTED', '2026-10-19 08:00:00+07', 'Tồn kho mở đầu khi bổ sung danh mục và mạng lưới chi nhánh (dữ liệu demo).'
FROM warehouses w WHERE w.code IN (SELECT DISTINCT site_code FROM sb_open_stock)
ON CONFLICT DO NOTHING;

CREATE TEMP TABLE sb_open_lines ON COMMIT DROP AS
SELECT s.qty, w.id AS warehouse_id, w.code AS site_code, v.id AS variant_id, v.sku, l.id AS location_id, v.unit_cost,
       md5('smartbook-expansion:receipt:' || w.code)::uuid AS receipt_id,
       md5('smartbook-expansion:line:' || w.code || ':' || v.sku)::uuid AS line_id
FROM sb_open_stock s
JOIN warehouses w ON w.code = s.site_code
JOIN book_variants v ON v.sku = s.sku
JOIN locations l ON l.warehouse_id = w.id AND l.location_code = s.location_code;

INSERT INTO goods_receipt_items (id, goods_receipt_id, variant_id, location_id, quantity, actual_quantity, unit_cost, condition_grade, note)
SELECT line_id, receipt_id, variant_id, location_id, qty, qty, unit_cost, 'NEW', 'Tồn kho mở đầu'
FROM sb_open_lines
ON CONFLICT DO NOTHING;

-- Ledger first; balances only grow by what this run actually posted.
WITH posted AS (
  INSERT INTO stock_movements (movement_number, movement_type, movement_status, warehouse_id, variant_id, to_location_id, quantity, unit_cost, reason_code, source_service, reference_type, reference_id, idempotency_key, metadata)
  SELECT 'MOV-OPEN-' || upper(substr(md5(site_code || ':' || sku), 1, 12)), 'INBOUND', 'POSTED', warehouse_id, variant_id, location_id, qty, unit_cost, 'OPENING_STOCK', 'inventory-service', 'GOODS_RECEIPT', receipt_id,
         'expansion-open:' || site_code || ':' || sku, jsonb_build_object('goods_receipt_item_id', line_id, 'movement_bucket', 'PUTAWAY')
  FROM sb_open_lines
  ON CONFLICT DO NOTHING
  RETURNING warehouse_id, variant_id, to_location_id, quantity
)
INSERT INTO stock_balances (warehouse_id, variant_id, location_id, on_hand_qty, available_qty)
SELECT warehouse_id, variant_id, to_location_id, quantity, quantity FROM posted
ON CONFLICT (variant_id, location_id) DO UPDATE
  SET on_hand_qty = stock_balances.on_hand_qty + EXCLUDED.on_hand_qty,
      available_qty = stock_balances.available_qty + EXCLUDED.available_qty,
      updated_at = now();

COMMIT;
`);

writeFileSync(outPath, `${sql.join("\n")}\n`);
console.log(`Wrote ${outPath}: ${books.length} books, ${BRANCHES.length} new branches, ${WAREHOUSES.length} new warehouses, ${rows.length} opening-stock lines for new books.`);
