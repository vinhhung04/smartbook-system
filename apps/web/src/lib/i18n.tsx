interface I18nContextValue {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nContextValue>({
  locale: 'vi',
  setLocale: () => {},
  t: (key) => key,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    const saved = localStorage.getItem('smartbook-locale') as Locale | null;
    return saved || 'vi';
  });

  useEffect(() => {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = locale;
    }
  }, [locale]);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    localStorage.setItem('smartbook-locale', l);
  }, []);

  const t = useCallback((key: string): string => {
    return translations[locale]?.[key] || translations.vi[key] || key;
  }, [locale]);

  return (
    <I18nContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}

export function LanguageToggle({ className }: { className?: string }) {
  const { locale, setLocale } = useI18n();
  return (
    <button
      onClick={() => setLocale(locale === 'vi' ? 'en' : 'vi')}
      className={`inline-flex items-center justify-center gap-1.5 px-2.5 h-8 rounded-[8px] text-[11px] text-slate-500 hover:bg-slate-100 dark:hover:bg-slate-800 dark:text-slate-400 transition-all duration-140 ${className || ''}`}
      style={{ fontWeight: 600 }}
      title={locale === 'vi' ? 'Switch to English' : 'Chuyển sang Tiếng Việt'}
      aria-label={locale === 'vi' ? 'Switch to English' : 'Chuyển sang Tiếng Việt'}
    >
      {locale === 'vi' ? 'VI' : 'EN'}
    </button>
  );
}
